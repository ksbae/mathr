# Inverse complementary error function: returns x with erfc(x) = p,
# for 0 < p < 2.
#
# erfc(x) = 2 * Phi(-x*sqrt(2)), so x = -Phi^-1(p/2) / sqrt(2). The
# normal quantile is the Cephes routine ndtri (Moshier), as
# redistributed in ALGLIB specialfunctions.cs (invnormalcdf): a
# rational approximation in the central region and a second one in
# sqrt(-2 log p) for the tails.
inverfc = function(p)
{
    if (p >= 2.0) return (-100.)
    if (p <= 0.0) return (100.)

    horner = function(co, u) { r = 0; for (i in length(co):1) r = co[i] + u*r; r }

    ndtri = function(y0) {
      EXPM2 = 0.13533528323661269189   # exp(-2)
      S2PI  = 2.50662827463100050242   # sqrt(2 pi)

      code = TRUE
      y = y0
      if (y > 1.0 - EXPM2) { y = 1.0 - y; code = FALSE }

      if (y > EXPM2) {                 # central region
        P0 = c(-1.23916583867381258016, 13.9312609387279679503,
               -56.6762857469070293439, 98.0010754185999661536,
               -59.9633501014107895267)
        Q0 = c(-1.18331621121330003142, 15.9056225126211695515,
               -82.0372256168333339912, 200.260212380060660359,
               -225.462687854119370527, 86.3602421390890590575,
               4.67627912898881538453, 1.95448858338141759834, 1.0)
        y  = y - 0.5
        y2 = y*y
        x  = y + y*y2*horner(P0, y2)/horner(Q0, y2)
        return (x * S2PI)
      }

      x  = sqrt(-2.0*log(y))           # tails
      x0 = x - log(x)/x
      z  = 1.0/x
      if (x < 8.0) {
        P1 = c(-8.57456785154685413611e-4, -3.50424626827848203418e-2,
               -1.40256079171354495875e-1, 2.18663306850790267539,
               14.6849561928858024014, 44.0805073893200834700,
               57.1628192246421288162, 31.5251094599893866154,
               4.05544892305962419923)
        Q1 = c(-9.33259480895457427372e-4, -3.80806407691578277194e-2,
               -1.42182922854787788574e-1, 2.50464946208309415979,
               15.0425385692907503408, 41.3172038254672030440,
               45.3907635128879210584, 15.7799883256466749731, 1.0)
        x1 = z*horner(P1, z)/horner(Q1, z)
      } else {
        P2 = c(6.23974539184983293730e-9, 2.65806974686737550832e-6,
               3.01581553508235416007e-4, 1.23716634817820021358e-2,
               2.01485389549179081538e-1, 1.33303460815807542389,
               3.93881025292474443415, 6.91522889068984211695,
               3.23774891776946035970)
        Q2 = c(6.79019408009981274425e-9, 2.89247864745380683936e-6,
               3.28014464682127739104e-4, 1.34204006088543189037e-2,
               2.16236993594496635890e-1, 1.37702099489081330271,
               3.67983563856160859403, 6.02427039364742014255, 1.0)
        x1 = z*horner(P2, z)/horner(Q2, z)
      }
      x = x0 - x1
      if (code) x = -x
      return (x)
    }

    return (-ndtri(p/2.0) / 1.4142135623730950488)
}
